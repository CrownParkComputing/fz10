#!/usr/bin/env python3
"""Generate Crown Park Computing's own placeholder case art.

Replaces the third-party scans previously used as sample textures. Everything
drawn here is generated from this script, so its provenance is this file.

Run:  python3 docs/make-placeholder-art.py
"""
from PIL import Image, ImageDraw, ImageFont
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEX = ROOT / "app/assets/dvd-case/textures"
ASSETS = ROOT / "app/assets"
BOLD = "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf"
REG = "/usr/share/fonts/TTF/DejaVuSans.ttf"

INK = (14, 18, 28)
PAPER = (238, 240, 245)
ACCENT = (228, 92, 48)
STEEL = (92, 112, 140)


def font(path, size):
    return ImageFont.truetype(path, size)


def centred(d, box, text, f, fill):
    x0, y0, x1, y1 = box
    l, t, r, b = d.textbbox((0, 0), text, font=f)
    d.text((x0 + (x1 - x0 - (r - l)) / 2 - l, y0 + (y1 - y0 - (b - t)) / 2 - t),
           text, font=f, fill=fill)


def gradient(size, top, bottom):
    w, h = size
    img = Image.new("RGB", (1, h))
    px = img.load()
    for y in range(h):
        k = y / max(h - 1, 1)
        px[0, y] = tuple(round(top[i] + (bottom[i] - top[i]) * k) for i in range(3))
    return img.resize((w, h))


def wrap():
    """The 284 x 190 mm sleeve: back cover | spine | front cover.

    UV layout from docs/case-view-notes.md: u 0..0.4825 one cover,
    0.4825..0.5175 the 14 mm spine, 0.5175..1.0 the other cover. The cover at
    u > 0.52 is the front.
    """
    W, H = 2560, 1712
    img = gradient((W, H), (26, 32, 48), (10, 12, 20))
    d = ImageDraw.Draw(img)
    back = (0, 0, int(W * 0.4825), H)
    spine = (int(W * 0.4825), 0, int(W * 0.5175), H)
    front = (int(W * 0.5175), 0, W, H)

    # Front cover: title block over a geometric field.
    fx0, _, fx1, _ = front
    fw = fx1 - fx0
    for i in range(14):
        k = i / 13
        x = fx0 + fw * 0.08 + fw * 0.84 * k
        d.line([(x, H * 0.16), (x, H * 0.52)],
               fill=tuple(round(STEEL[j] * (0.25 + 0.55 * k)) for j in range(3)),
               width=max(2, int(fw * 0.008)))
    d.rectangle([fx0 + fw * 0.08, H * 0.58, fx1 - fw * 0.08, H * 0.60], fill=ACCENT)
    centred(d, (fx0, H * 0.62, fx1, H * 0.74), "FZ-10", font(BOLD, int(H * 0.11)), PAPER)
    centred(d, (fx0, H * 0.76, fx1, H * 0.82), "SAMPLE DISC",
            font(REG, int(H * 0.035)), STEEL)
    centred(d, (fx0, H * 0.86, fx1, H * 0.92), "CROWN PARK COMPUTING",
            font(REG, int(H * 0.022)), STEEL)

    # Spine.
    sx0, _, sx1, _ = spine
    d.rectangle(spine, fill=(20, 24, 36))
    strip = Image.new("RGB", (H, sx1 - sx0), (20, 24, 36))
    sd = ImageDraw.Draw(strip)
    centred(sd, (0, 0, H, sx1 - sx0), "FZ-10   SAMPLE DISC",
            font(BOLD, int((sx1 - sx0) * 0.46)), PAPER)
    img.paste(strip.rotate(-90, expand=True), (sx0, 0))

    # Back cover: blurb box and three screenshot panels.
    bx0, _, bx1, _ = back
    bw = bx1 - bx0
    d.rectangle([bx0 + bw * 0.08, H * 0.10, bx1 - bw * 0.08, H * 0.40],
                outline=STEEL, width=3)
    centred(d, (bx0, H * 0.20, bx1, H * 0.30),
            "PLACEHOLDER ARTWORK", font(BOLD, int(H * 0.045)), PAPER)
    panel_w = bw * 0.24
    for i in range(3):
        x = bx0 + bw * 0.08 + i * (panel_w + bw * 0.06)
        d.rectangle([x, H * 0.48, x + panel_w, H * 0.48 + panel_w * 0.75],
                    fill=(30, 38, 56), outline=STEEL, width=2)
    centred(d, (bx0, H * 0.78, bx1, H * 0.86),
            "Generated by docs/make-placeholder-art.py",
            font(REG, int(H * 0.020)), STEEL)
    centred(d, (bx0, H * 0.86, bx1, H * 0.92),
            "(c) 2026 Crown Park Computing - MIT",
            font(REG, int(H * 0.020)), STEEL)

    out = TEX / "case-wrap-sample.jpg"
    img.save(out, quality=92)
    return out, img.size


def disc():
    """Square disc label; UV is a plain 0..1 square across the disc face."""
    S = 1024
    img = Image.new("RGB", (S, S), (10, 12, 20))
    d = ImageDraw.Draw(img)
    c = S / 2
    d.ellipse([0, 0, S, S], fill=(24, 30, 46))
    for i, r in enumerate((0.47, 0.42, 0.37)):
        d.ellipse([c - S * r, c - S * r, c + S * r, c + S * r],
                  outline=STEEL if i else ACCENT, width=3)
    # Centre hole and clamping ring first, so no text can land under them.
    d.ellipse([c - S * 0.17, c - S * 0.17, c + S * 0.17, c + S * 0.17], fill=(16, 20, 32))
    d.ellipse([c - S * 0.075, c - S * 0.075, c + S * 0.075, c + S * 0.075], fill=(8, 10, 16))
    # Label text sits in the two bands clear of the hub (hub spans 0.33..0.67).
    centred(d, (0, S * 0.15, S, S * 0.26), "FZ-10", font(BOLD, int(S * 0.12)), PAPER)
    centred(d, (0, S * 0.27, S, S * 0.32), "SAMPLE DISC", font(REG, int(S * 0.036)), STEEL)
    centred(d, (0, S * 0.71, S, S * 0.77), "CROWN PARK COMPUTING",
            font(REG, int(S * 0.026)), STEEL)
    centred(d, (0, S * 0.79, S, S * 0.84), "PLACEHOLDER ARTWORK",
            font(REG, int(S * 0.023)), STEEL)
    out = TEX / "disc-sample.jpg"
    img.save(out, quality=92)
    return out, img.size


def mark():
    """Our own mark, replacing the 3DO wordmark compiled into the binary."""
    S = 512
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    c = S / 2
    d.ellipse([S * 0.06, S * 0.06, S * 0.94, S * 0.94], fill=INK + (255,))
    d.ellipse([S * 0.06, S * 0.06, S * 0.94, S * 0.94], outline=ACCENT + (255,), width=10)
    centred(d, (0, S * 0.30, S, S * 0.52), "FZ", font(BOLD, int(S * 0.30)), PAPER + (255,))
    d.rectangle([S * 0.30, S * 0.57, S * 0.70, S * 0.60], fill=ACCENT + (255,))
    centred(d, (0, S * 0.62, S, S * 0.74), "10", font(BOLD, int(S * 0.16)), STEEL + (255,))
    out = ASSETS / "cpc-mark.png"
    img.save(out)
    return out, img.size


# --- the artwork template -------------------------------------------------
#
# One printed sleeve is 284 x 190 mm: a 135 mm back cover, a 14 mm spine and a
# 135 mm front cover. Everything below is stated in millimetres and converted
# once, so the numbers in docs/CASE-ARTWORK.md and the numbers here are the
# same numbers.

SLEEVE_W_MM = 284.0
SLEEVE_H_MM = 190.0
COVER_W_MM = 135.0
SPINE_W_MM = 14.0
BLEED_MM = 3.0      # trimmed off; art must run into it
SAFE_MM = 5.0       # keep text inside this of any trim edge

PX_PER_MM = 2560.0 / SLEEVE_W_MM   # the sheet the renderer wants, 2560 x 1712


def mm(v):
    return v * PX_PER_MM


def cover(front):
    """One cover panel on its own: 135 x 190 mm at the sheet's resolution.

    This is what CaseArt.front and CaseArt.back take - a single panel, not a
    whole wrap. Handing a full sleeve to a cover slot letterboxes it.
    """
    W, H = round(mm(COVER_W_MM)), round(mm(SLEEVE_H_MM))
    img = gradient((W, H), (26, 32, 48), (10, 12, 20))
    d = ImageDraw.Draw(img)
    if front:
        for i in range(14):
            k = i / 13
            x = W * 0.10 + W * 0.80 * k
            d.line([(x, H * 0.14), (x, H * 0.46)],
                   fill=tuple(round(STEEL[j] * (0.25 + 0.55 * k)) for j in range(3)),
                   width=max(2, int(W * 0.012)))
        d.rectangle([W * 0.10, H * 0.53, W * 0.90, H * 0.55], fill=ACCENT)
        centred(d, (0, H * 0.57, W, H * 0.69), "FZ-10", font(BOLD, int(H * 0.10)), PAPER)
        centred(d, (0, H * 0.71, W, H * 0.77), "SAMPLE DISC", font(REG, int(H * 0.032)), STEEL)
        centred(d, (0, H * 0.85, W, H * 0.90), "CROWN PARK COMPUTING",
                font(REG, int(H * 0.020)), STEEL)
    else:
        d.rectangle([W * 0.10, H * 0.10, W * 0.90, H * 0.38], outline=STEEL, width=3)
        centred(d, (0, H * 0.20, W, H * 0.28), "PLACEHOLDER", font(BOLD, int(H * 0.040)), PAPER)
        panel = W * 0.24
        for i in range(3):
            x = W * 0.10 + i * (panel + W * 0.08)
            d.rectangle([x, H * 0.46, x + panel, H * 0.46 + panel * 0.75],
                        fill=(30, 38, 56), outline=STEEL, width=2)
        centred(d, (0, H * 0.80, W, H * 0.85),
                "Generated by docs/make-placeholder-art.py",
                font(REG, int(H * 0.018)), STEEL)
        centred(d, (0, H * 0.86, W, H * 0.91),
                "(c) 2026 Crown Park Computing - MIT", font(REG, int(H * 0.018)), STEEL)
    out = TEX / ("cover-front-sample.jpg" if front else "cover-back-sample.jpg")
    img.save(out, quality=92)
    return out, img.size


def template():
    """The guide artists lay a sleeve out on. Not shipped in the app."""
    W, H = 2560, 1712
    img = Image.new("RGB", (W, H), (248, 248, 250))
    d = ImageDraw.Draw(img)
    spine0 = mm(COVER_W_MM)
    spine1 = mm(COVER_W_MM + SPINE_W_MM)
    bleed = mm(BLEED_MM)
    safe = mm(BLEED_MM + SAFE_MM)

    for x0, x1, label in ((0, spine0, "BACK COVER  135 mm"),
                          (spine1, W, "FRONT COVER  135 mm")):
        d.rectangle([x0, 0, x1, H], fill=(236, 239, 245))
        centred(d, (x0, H * 0.46, x1, H * 0.54), label, font(BOLD, 34), (70, 84, 110))
    d.rectangle([spine0, 0, spine1, H], fill=(214, 220, 232))

    # Trim, bleed and safe area.
    d.rectangle([bleed, bleed, W - bleed, H - bleed], outline=(200, 60, 40), width=4)
    d.rectangle([safe, safe, W - safe, H - safe], outline=(40, 140, 90), width=3)
    for x in (spine0, spine1):
        d.line([(x, 0), (x, H)], fill=(120, 130, 150), width=2)

    key = [
        ("sheet  284 x 190 mm, 2560 x 1712 px at %.1f px/mm" % PX_PER_MM, (70, 84, 110)),
        ("red: trim, %.0f mm bleed - art must run to the sheet edge" % BLEED_MM, (200, 60, 40)),
        ("green: safe area, keep text %.0f mm inside the trim" % SAFE_MM, (40, 140, 90)),
        ("grey: the %.0f mm spine" % SPINE_W_MM, (120, 130, 150)),
    ]
    for i, (line, colour) in enumerate(key):
        d.text((safe + 14, safe + 14 + i * 40), line, font=font(REG, 28), fill=colour)
    centred(d, (spine0, H * 0.02, spine1, H * 0.08), "SPINE", font(BOLD, 22), (70, 84, 110))

    out = ROOT / "docs" / "case-artwork-template.png"
    img.save(out)
    return out, img.size


if __name__ == "__main__":
    jobs = [wrap, disc, mark, template,
            lambda: cover(True), lambda: cover(False)]
    for fn in jobs:
        path, size = fn()
        print(f"{path.relative_to(ROOT)}  {size[0]}x{size[1]}")
