// --- random programs ------------------------------------------------------

fn random_operand(rng: &mut SplitMix) -> u16 {
    let r = rng.next();
    if r.is_multiple_of(4) {
        // An address operand aimed at the hardware ports, sometimes marked.
        return (0x8000 | ((r >> 8) & 0xc00) | (0xd0 + (r >> 16) % 0x30)) as u16;
    }
    (r >> 20) as u16
}

fn build_random_program(dsp: &mut Dsp, rng: &mut SplitMix) {
    fn put(dsp: &mut Dsp, address: &mut u16, word: u16) {
        dsp.write_program(*address, word);
        *address += 1;
    }
    let mut address = 0u16;
    while address < 1024 {
        let r = rng.next();
        let w = (r >> 16) as u16;
        match r % 16 {
            0..=5 => {
                let word = w & 0x7fff;
                put(dsp, &mut address, word);
                let mut n = (word >> 13) & 3;
                if n == 0 {
                    n = ((r >> 40) % 3) as u16;
                }
                let mut i = 0;
                while i < n && address < 1024 {
                    let operand = random_operand(rng);
                    put(dsp, &mut address, operand);
                    i += 1;
                }
            }
            6 | 7 => put(dsp, &mut address, w),
            8 | 9 => put(dsp, &mut address, w | 0x8000),
            10 => put(dsp, &mut address, SLEEP),
            11 => put(
                dsp,
                &mut address,
                (0x8000 | (((r >> 40) & 0x7f) << 7)) as u16,
            ),
            12 | 13 | 15 => {
                let word = match r % 16 {
                    12 => 0x9bfe | (w & 1),
                    13 => 0x9000 | (w & 0x7ff),
                    _ => {
                        0x9800
                            | if w & 1 != 0 {
                                0x3e0 | (w >> 11)
                            } else {
                                w & 0x7ff
                            }
                    }
                };
                put(dsp, &mut address, word);
                if address < 1024 {
                    let operand = random_operand(rng);
                    put(dsp, &mut address, operand);
                }
            }
            _ => put(
                dsp,
                &mut address,
                (0x8000 | (u64::from(8 + (w % 24)) << 10) | ((r >> 40) & 0x3ff)) as u16,
            ),
        }
    }
}

fn cpu_meddle(dsp: &mut Dsp, rng: &mut SplitMix, hash: &mut Fnv) {
    let n = rng.next() % 5;
    for _ in 0..n {
        let r = rng.next();
        let address = (if r & 1 != 0 {
            0x70 + (r >> 8) % 13
        } else {
            (r >> 8) & 0x1ff
        }) as u16;
        dsp.write_data(address, (r >> 32) as u16);
    }
    if rng.next().is_multiple_of(3) {
        dsp.write_semaphore(rng.next() as u32);
    }
    if rng.next().is_multiple_of(7) {
        dsp.reset();
    }
    let reads = rng.next();
    hash.add(u32::from(dsp.read_data((reads & 0x3ff) as u16)));
    hash.add(u32::from(dsp.read_data((0x3eb + (reads >> 20) % 5) as u16)));
}

fn fuzz_one(seed: u64) -> (u32, u64) {
    let mut rng = SplitMix(seed);
    let mut dsp = Dsp::new();
    let mut host = MockHost::default();
    build_random_program(&mut dsp, &mut rng);
    for address in 0..1024u16 {
        let r = rng.next();
        let value = if r & 3 == 0 {
            (r >> 16) as u16
        } else {
            ((r >> 16) & 0x3ff) as u16
        };
        dsp.poke_raw_data(address, value);
    }
    let mut hash = Fnv::new();
    cpu_meddle(&mut dsp, &mut rng, &mut hash);
    dsp.set_running(true);
    for _ in 0..3 {
        hash.add(dsp.run(&mut host));
        hash.add(dsp.pc());
        hash.add(dsp.read_semaphore());
        cpu_meddle(&mut dsp, &mut rng, &mut hash);
    }
    for address in 0..1024u16 {
        hash.add(u32::from(dsp.peek_raw_data(address)));
    }
    for &(kind, channel, value) in &host.events {
        hash.add(u32::from(kind));
        hash.add(u32::from(channel));
        hash.add(u32::from(value));
    }
    (host.events.len() as u32, hash.0)
}

#[test]
fn random_programs_match_the_reference_core() {
    let mismatches: Vec<u64> = FUZZ_EXPECTED
        .iter()
        .filter(|&&(seed, events, hash)| fuzz_one(seed) != (events, hash))
        .map(|&(seed, _, _)| seed)
        .collect();
    assert!(
        mismatches.is_empty(),
        "seeds that differ from the reference: {mismatches:?}"
    );
}

