/// A host that answers deterministically and records every call as
/// (kind, channel, value): 1 next, 2 peek, 3 input status, 4 output status,
/// 5 output, 6 interrupt.
struct MockHost {
    state: u32,
    events: Vec<(u8, u16, u16)>,
}

impl Default for MockHost {
    fn default() -> Self {
        Self {
            state: 0x1357_9bdf,
            events: Vec::new(),
        }
    }
}

impl DspHost for MockHost {
    fn input_next(&mut self, channel: u16) -> u16 {
        self.state = self
            .state
            .wrapping_mul(1_103_515_245)
            .wrapping_add(12345)
            .wrapping_add(u32::from(channel));
        let value = (self.state >> 16) as u16;
        self.events.push((1, channel, value));
        value
    }
    fn input_peek(&mut self, channel: u16) -> u16 {
        let value = ((self.state >> 8) as u16) ^ channel.wrapping_mul(0x1111);
        self.events.push((2, channel, value));
        value
    }
    fn input_status(&mut self, channel: u16) -> u16 {
        let value = ((usize::from(channel) + self.events.len()) & 3) as u16;
        self.events.push((3, channel, value));
        value
    }
    fn output_status(&mut self, channel: u16) -> u16 {
        let value = 0x10 + channel;
        self.events.push((4, channel, value));
        value
    }
    fn output(&mut self, channel: u16, value: u16) {
        self.events.push((5, channel, value));
    }
    fn audio_interrupt(&mut self) {
        self.events.push((6, 0, 0));
    }
}

struct Fnv(u64);

impl Fnv {
    fn new() -> Self {
        Self(0xcbf2_9ce4_8422_2325)
    }
    fn add(&mut self, value: u32) {
        for byte in value.to_le_bytes() {
            self.0 ^= u64::from(byte);
            self.0 = self.0.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
}

struct SplitMix(u64);

impl SplitMix {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        z ^ (z >> 31)
    }
}

// The same little assembler the probe used.
fn arith(numops: u16, m2sel: u16, muxa: u16, muxb: u16, alu: u16, bs: u16) -> u16 {
    (numops << 13) | (m2sel << 12) | (muxa << 10) | (muxb << 8) | (alu << 4) | bs
}
fn imm(value: i32) -> u16 {
    0xc000 | (value as u16 & 0x1fff)
}
fn addr(address: u16) -> u16 {
    0x8000 | address
}
fn jump(target: u16) -> u16 {
    0x8400 | target
}
fn branch(condition: u16, target: u16) -> u16 {
    0x8000 | (condition << 10) | target
}
fn move_addr(address: u16) -> u16 {
    0x9800 | address
}

fn load(dsp: &mut Dsp, program: &[u16]) {
    for (address, &word) in program.iter().enumerate() {
        dsp.write_program(address as u16, word);
    }
}

struct Scenario<'a> {
    program: &'a [u16],
    raw: &'a [(u16, u16)],
    cpu: &'a [(u16, u16)],
    semaphore: Option<u32>,
    passes: usize,
}

struct Outcome {
    dacs: Vec<u32>,
    pc: u32,
    semaphore: u32,
    ports: Vec<u16>,
    events: Vec<(u8, u16, u16)>,
    upper: Vec<(u16, u16)>,
    data_hash: u64,
}

fn run_scenario(scenario: &Scenario) -> Outcome {
    let mut dsp = Dsp::new();
    let mut host = MockHost::default();
    load(&mut dsp, scenario.program);
    for &(address, value) in scenario.raw {
        dsp.poke_raw_data(address, value);
    }
    for &(address, value) in scenario.cpu {
        dsp.write_data(address, value);
    }
    if let Some(value) = scenario.semaphore {
        dsp.write_semaphore(value);
    }
    dsp.set_running(true);
    let dacs = (0..scenario.passes).map(|_| dsp.run(&mut host)).collect();
    let mut hash = Fnv::new();
    let mut upper = Vec::new();
    for address in 0..1024u16 {
        let word = dsp.peek_raw_data(address);
        hash.add(u32::from(word));
        if address >= 0x100 && word != 0 {
            upper.push((address, word));
        }
    }
    Outcome {
        dacs,
        pc: dsp.pc(),
        semaphore: dsp.read_semaphore(),
        ports: (0x3eb..=0x3ef)
            .map(|address| dsp.read_data(address))
            .collect(),
        events: host.events,
        upper,
        data_hash: hash.0,
    }
}

#[test]
fn alu_operations_and_the_flags_they_leave() {
    for &(op, a, b, result, mask) in ALU_TABLE {
        let mut got_mask = 0u32;
        let mut got_result = 0u16;
        for condition in 8..32u16 {
            let mut dsp = Dsp::new();
            load(
                &mut dsp,
                &[
                    arith(3, 0, 1, 2, op, 0),
                    addr(0x10),
                    addr(0x11),
                    imm(0x3ff),
                    branch(condition, 8),
                    move_addr(0x3fe),
                    imm(0),
                    jump(10),
                    move_addr(0x3fe),
                    imm(1),
                    SLEEP,
                ],
            );
            dsp.write_data(0x10, a);
            dsp.write_data(0x11, b);
            dsp.set_running(true);
            let out = dsp.run(&mut NullHost);
            got_result = (out >> 16) as u16;
            if out & 0xffff == 1 {
                got_mask |= 1 << (condition - 8);
            }
        }
        assert_eq!(
            (got_result, got_mask),
            (result, mask),
            "ALU op {op} with {a:#06x}, {b:#06x}"
        );
    }
}

