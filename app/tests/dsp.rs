//! DSPP tests.
//!
//! The first three are ported from the reference core's `tests/test_dsp.cpp`.
//! They run real instruction streams rather than reaching into the decoder,
//! which pins the contract between arithmetic flags, conditional control flow,
//! operand words and the memory-mapped DACs.
//!
//! Everything named `oracle_*` and every table below was recorded by running
//! the same programs on the C++ reference core (a probe linked against its
//! static library): ALU operations and the flags they leave, the barrel
//! shifter, the multiplier forms, operand modes and write-back selection,
//! FIFO traffic through a mock host, the semaphore, and 400 random programs
//! compared by a hash of everything observable.
