#[test]
fn clio_window_program_views_and_mirrors() {
    let mut dsp = Dsp::new();
    // Two words per CPU word: high half first.
    assert!(dsp.cpu_window_write(window::PROGRAM_PAIRS + 4, 0x1111_2222));
    assert_eq!(dsp.peek_program(2), 0x1111);
    assert_eq!(dsp.peek_program(3), 0x2222);
    // The 0x400 bit mirrors.
    assert!(dsp.cpu_window_write(window::PROGRAM_PAIRS + 0x400 + 8, 0x3333_4444));
    assert_eq!(dsp.peek_program(4), 0x3333);
    assert_eq!(dsp.peek_program(5), 0x4444);
    // One word per CPU word; the 0x800 bit mirrors.
    assert!(dsp.cpu_window_write(window::PROGRAM_SINGLE + 0x40, 0xffff_5555));
    assert_eq!(dsp.peek_program(0x10), 0x5555);
    assert!(dsp.cpu_window_write(window::PROGRAM_SINGLE + 0x800 + 0x44, 0x6666));
    assert_eq!(dsp.peek_program(0x11), 0x6666);
    assert!(dsp.cpu_window_write(0x27fc, 0x7777));
    assert_eq!(dsp.peek_program(0x1ff), 0x7777);
}

#[test]
fn clio_window_data_views_semaphore_reset_and_run() {
    let mut dsp = Dsp::new();
    assert!(dsp.cpu_window_write(window::DATA_PAIRS + 0x10, 0xaaaa_bbbb));
    assert_eq!(dsp.read_data(0x08), 0xaaaa);
    assert_eq!(dsp.read_data(0x09), 0xbbbb);
    assert!(dsp.cpu_window_write(window::DATA_SINGLE + 0x0c, 0x1234_cccc));
    assert_eq!(dsp.read_data(0x03), 0xcccc);
    // Stores into the read views are swallowed.
    assert!(dsp.cpu_window_write(window::READ_PAIRS, 0x1234_5678));
    assert!(dsp.cpu_window_write(window::READ_SINGLE + 0x3fc, 1));

    dsp.poke_raw_data(0x300, 0x0102);
    dsp.poke_raw_data(0x301, 0x0304);
    dsp.poke_raw_data(0x3fe, 0x0506);
    assert_eq!(dsp.cpu_window_read(window::READ_PAIRS), Some(0x0102_0304));
    assert_eq!(dsp.cpu_window_read(window::READ_SINGLE + 4), Some(0x0304));
    assert_eq!(
        dsp.cpu_window_read(window::READ_SINGLE + 0xfe * 4),
        Some(0x0506)
    );

    assert!(dsp.cpu_window_write(window::SEMAPHORE, 0x0001_0042));
    assert_eq!(dsp.cpu_window_read(window::SEMAPHORE), Some(0x0008_0042));

    assert!(dsp.cpu_window_write(window::RUN, 1));
    assert!(dsp.running());
    dsp.run(&mut NullHost);
    assert_eq!(dsp.pc(), 1);
    assert!(dsp.cpu_window_write(window::RESET, 0));
    assert_eq!(dsp.pc(), 0);
    assert!(dsp.cpu_window_write(window::RUN, 0));
    assert!(!dsp.running());

    // Not the DSPP's: CLIO keeps these in its raw window image.
    assert!(!dsp.cpu_window_write(window::NOISE, 5));
    assert!(!dsp.cpu_window_write(window::BASE, 5));
    assert_eq!(dsp.cpu_window_read(window::NOISE), None);
    assert_eq!(dsp.cpu_window_read(window::PROGRAM_PAIRS), None);
    assert_eq!(dsp.cpu_window_read(window::DATA_SINGLE), None);
}

#[test]
fn garbage_programs_never_hang_or_panic() {
    // Every word value as the whole program, with operands drawn from it too.
    let mut dsp = Dsp::new();
    for word in (0..=u16::MAX).step_by(7) {
        dsp.write_program(word & 0x3ff, word);
        dsp.write_program((word ^ 0x155) & 0x3ff, word.rotate_left(5));
    }
    for address in 0..1024u16 {
        dsp.poke_raw_data(address, address.wrapping_mul(0x9e37));
    }
    dsp.set_running(true);
    let mut host = MockHost::default();
    for _ in 0..4 {
        dsp.run(&mut host);
    }
    const { assert!(MAX_STEPS_PER_PASS == 1 << 20) };
}

