#[test]
fn power_on_program_memory_is_sleep_and_a_started_dsp_halts_at_once() {
    let mut dsp = Dsp::new();
    assert!(!dsp.running());
    for address in [0u16, 1, 0x200, 0x3ff] {
        assert_eq!(dsp.peek_program(address), SLEEP);
    }
    dsp.set_running(true);
    let mut host = MockHost::default();
    assert_eq!(dsp.run(&mut host), 0);
    assert_eq!(dsp.pc(), 1);
    assert!(host.events.is_empty());
}

#[test]
fn a_stopped_dsp_runs_nothing_and_returns_the_dacs_as_they_stand() {
    let mut dsp = Dsp::new();
    // Would raise the interrupt and change the DACs if it ran.
    for (address, word) in [0x9bee, 0xc001, 0x9bfe, 0xc123, SLEEP]
        .into_iter()
        .enumerate()
    {
        dsp.write_program(address as u16, word);
    }
    dsp.poke_raw_data(0x3fe, 0x1111);
    dsp.poke_raw_data(0x3ff, 0x2222);
    let mut host = MockHost::default();
    assert_eq!(dsp.run(&mut host), 0x2222_1111);
    assert!(host.events.is_empty());

    dsp.set_running(true);
    assert_eq!(dsp.run(&mut host), 0x2222_0123);
    assert_eq!(host.events, [(6, 0, 0)]);
    assert_eq!(dsp.dac_words(), 0x2222_0123);
}

#[test]
fn reset_restarts_the_sequencer_but_keeps_memory_and_run_state() {
    let mut dsp = Dsp::new();
    dsp.write_program(0, 0x8400 | 5); // jump 5 - leaves the PC past 5 after the pass
    dsp.write_data(0x10, 0x4444);
    dsp.set_running(true);
    dsp.run(&mut NullHost);
    assert_eq!(dsp.pc(), 6);
    dsp.reset();
    assert_eq!(dsp.pc(), 0);
    assert!(dsp.running());
    assert_eq!(dsp.read_data(0x10), 0x4444);
    assert_eq!(dsp.peek_program(0), 0x8400 | 5);
}

#[test]
fn cpu_data_writes_reach_only_the_low_bank() {
    let mut dsp = Dsp::new();
    dsp.write_data(0x05, 0x1111);
    dsp.write_data(0x7f, 0x2222);
    dsp.write_data(0x80, 0x3333); // the DSPP's half: ignored
    dsp.write_data(0x105, 0x4444); // bit 7 clear: folds onto 0x05
    assert_eq!(dsp.read_data(0x05), 0x4444);
    assert_eq!(dsp.read_data(0x7f), 0x2222);
    assert_eq!(dsp.read_data(0x80), 0);
    assert_eq!(dsp.peek_raw_data(0x105), 0);
}

